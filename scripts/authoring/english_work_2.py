def build(seed=20261109):
    rng = random.Random(seed)
    # Позиции правильного уравнены построением: 13, 13, 12, 12. Страница теста
    # ещё и перемешивает варианты при загрузке, это страховка на случай, если
    # перемешивание однажды уберут (CLAUDE.md, правило 2).
    positions = [0] * 13 + [1] * 13 + [2] * 12 + [3] * 12
    rng.shuffle(positions)
    out = []
    for item, pos in zip(Q, positions):
        opts = list(item["wrong"])
        opts.insert(pos, item["correct"])
        u = item["usage"]
        out.append({"q": item["q"], "options": opts, "correct": pos, "explain": item["explain"],
                    "usage": {"code": u["code"], "without": u["without"], "with": u["with_"],
                              "benefit": u["benefit"]}})
    return out


