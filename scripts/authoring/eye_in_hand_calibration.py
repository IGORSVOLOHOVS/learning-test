from eih_balance import B
for _i, (_c, _w) in B.items():
    Q[_i]["correct"], Q[_i]["wrong"] = _c, _w


def build(seed=20260919):
    rng = random.Random(seed)
    # positions balanced by construction: 13,13,12,12
    positions = [0] * 13 + [1] * 13 + [2] * 12 + [3] * 12
    rng.shuffle(positions)
    out = []
    for item, pos in zip(Q, positions):
        opts = list(item["wrong"])
        opts.insert(pos, item["correct"])
        u = item["usage"]
        out.append({"q": item["q"], "options": opts, "correct": pos, "explain": item["explain"],
                    "usage": {"code": u["code"], "without": u["without"], "with": u["with_"],
                              "benefit": u["benefit"]}})
    return out


