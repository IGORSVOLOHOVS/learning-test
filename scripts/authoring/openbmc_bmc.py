def build(seed=20261110):
    rng = random.Random(seed)
    # Позиции правильного уравнены построением: 13, 13, 12, 12. Страница теста
    # ещё и перемешивает варианты при загрузке (CLAUDE.md, правило 2).
    positions = [0] * 13 + [1] * 13 + [2] * 12 + [3] * 12
    rng.shuffle(positions)
    out = []
    for item, pos in zip(Q, positions):
        opts = list(item["wrong"])
        opts.insert(pos, item["correct"])
        u = item["usage"]
        out.append({"q": item["q"], "options": opts, "correct": pos, "explain": item["explain"],
                    "usage": {"code": u["code"], "without": u["without"], "with": u["with_"],
                              "benefit": u["benefit"]}})
    return out


def keep_images(qs, target):
    # Поле img вписывает scripts/images.py attach; при перегенерации не терять его.
    if not os.path.exists(target):
        return
    with open(target, encoding="utf-8") as f:
        old = json.load(f)
    for q, o in zip(qs, old):
        if "img" in o and o["q"] == q["q"]:
            q["img"] = o["img"]


